#!/usr/bin/env python3
"""Produce a deliberately typeset 6x9-in trade-paperback DOCX from canonical scenes.

The release PDF is converted from this DOCX, not from Pandoc's generic default.
Illustrations and character/object motifs are generated by artwork.py.
"""
from __future__ import annotations

import re
from pathlib import Path
from docx import Document
from docx.enum.section import WD_SECTION_START
from docx.enum.table import WD_CELL_VERTICAL_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH, WD_BREAK
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Inches, Pt, RGBColor

from common import ROOT, load_document, chapter_dirs, scene_files

INK = RGBColor(24, 43, 56)
AMBER = RGBColor(162, 105, 58)
MUTED = RGBColor(103, 119, 125)
SERIF = "Liberation Serif"
SANS = "Lato"

def set_font(style, name: str, size: float, color=None, bold=False):
    style.font.name = name
    style.font.size = Pt(size)
    style.font.bold = bold
    if color is not None:
        style.font.color.rgb = color
    # East Asian font declaration improves Word/LibreOffice parity.
    rPr = style.element.get_or_add_rPr()
    rFonts = rPr.rFonts
    if rFonts is None:
        rFonts = OxmlElement("w:rFonts")
        rPr.insert(0, rFonts)
    rFonts.set(qn("w:eastAsia"), name)

def set_cell_shading(cell, fill: str):
    tcPr=cell._tc.get_or_add_tcPr()
    shd=OxmlElement("w:shd")
    shd.set(qn("w:fill"), fill)
    tcPr.append(shd)

def page_field(paragraph):
    run = paragraph.add_run()
    b = OxmlElement("w:fldChar")
    b.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = " PAGE "
    e = OxmlElement("w:fldChar")
    e.set(qn("w:fldCharType"), "end")
    run._r.extend([b, instr, e])

def inline_runs(paragraph, text: str):
    """Keep a scene's guillemets and lightweight Markdown emphasis."""
    chunks=re.split(r"(\*\*[^*\n]+\*\*|\*[^*\n]+\*|_[^_\n]+_)",text)
    for chunk in chunks:
        if not chunk:
            continue
        if chunk.startswith("**") and chunk.endswith("**") and len(chunk)>4:
            run=paragraph.add_run(chunk[2:-2]);run.bold=True
        elif ((chunk.startswith("*") and chunk.endswith("*")) or (chunk.startswith("_") and chunk.endswith("_"))) and len(chunk)>2:
            run=paragraph.add_run(chunk[1:-1]);run.italic=True
        else:
            paragraph.add_run(chunk.replace("\\*", "*"))

def configure_styles(doc):
    styles=doc.styles
    normal=styles["Normal"]
    set_font(normal,SERIF,10.6,INK)
    pf=normal.paragraph_format
    pf.line_spacing=1.19
    pf.space_after=Pt(0)
    pf.space_before=Pt(0)
    pf.widow_control=True
    for key,size,color in [("Title",44,INK),("Heading 1",25,INK),("Heading 2",17,INK)]:
        style=styles[key]
        set_font(style,SANS,size,color,bold=(key!="Title"))
        style.paragraph_format.space_after=Pt(10)
        style.paragraph_format.keep_with_next=True

def add_body(doc, content: str):
    first=True
    for block in re.split(r"\n\s*\n",content.strip()):
        block=block.strip()
        if not block:
            continue
        if block in ("* * *", "***", "---"):
            p=doc.add_paragraph()
            p.alignment=WD_ALIGN_PARAGRAPH.CENTER
            p.paragraph_format.space_before=Pt(11)
            p.paragraph_format.space_after=Pt(11)
            r=p.add_run("◆  ◆  ◆")
            r.font.name=SANS;r.font.size=Pt(7);r.font.color.rgb=AMBER
            first=True
            continue
        if block.startswith("#"):
            p=doc.add_paragraph(block.lstrip("# ").strip(), style="Heading 2")
            first=True
            continue
        if re.match(r"^[-*] ",block):
            p=doc.add_paragraph(style="Normal")
            p.paragraph_format.left_indent=Inches(.22)
            p.paragraph_format.space_before=Pt(4)
            inline_runs(p,block.replace("\n"," "))
            first=False
            continue
        p=doc.add_paragraph(style="Normal")
        p.alignment=WD_ALIGN_PARAGRAPH.JUSTIFY
        p.paragraph_format.first_line_indent=Inches(0 if first else .19)
        p.paragraph_format.space_after=Pt(1)
        text=" ".join(line.strip() for line in block.splitlines())
        inline_runs(p,text)
        first=False

def make_header(section):
    # Do not leak the body running header/footer onto the full-art cover.
    section.header.is_linked_to_previous=False
    section.footer.is_linked_to_previous=False
    hdr=section.header
    hdr.distance=Inches(.36)
    p=hdr.paragraphs[0]
    p.alignment=WD_ALIGN_PARAGRAPH.CENTER
    r=p.add_run("B O T      ·      L'INNOVAZIONE NON CHIEDE PERMESSO")
    r.font.name=SANS;r.font.size=Pt(7.3);r.font.color.rgb=MUTED
    ftr=section.footer
    ftr.distance=Inches(.41)
    p=ftr.paragraphs[0]
    p.alignment=WD_ALIGN_PARAGRAPH.CENTER
    r=p.add_run("—  ")
    r.font.name=SANS;r.font.color.rgb=MUTED;r.font.size=Pt(9)
    page_field(p)
    r=p.add_run("  —")
    r.font.name=SANS;r.font.color.rgb=MUTED;r.font.size=Pt(9)

def text_par(doc,text,size=10,color=INK,space=0,align=WD_ALIGN_PARAGRAPH.LEFT):
    p=doc.add_paragraph()
    p.alignment=align
    p.paragraph_format.space_after=Pt(space)
    r=p.add_run(text)
    r.font.name=SANS;r.font.size=Pt(size);r.font.color.rgb=color
    return p

def add_title_pages(doc, chapters, version, art_dir):
    cover = art_dir / "cover.png"
    if not cover.exists():
        raise RuntimeError(f"Missing cover art: {cover}")
    section=doc.sections[0]
    section.page_width=Inches(6);section.page_height=Inches(9)
    section.top_margin=Inches(.14);section.bottom_margin=Inches(.06)
    section.left_margin=Inches(.14);section.right_margin=Inches(.14)
    section.header_distance=Inches(0);section.footer_distance=Inches(0)
    p=doc.add_paragraph()
    p.alignment=WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_after=Pt(0)
    p.paragraph_format.space_before=Pt(0)
    p.add_run().add_picture(str(cover),width=Inches(5.70),height=Inches(8.55))

    section=doc.add_section(WD_SECTION_START.NEW_PAGE)
    section.page_width=Inches(6);section.page_height=Inches(9)
    section.left_margin=Inches(.87);section.right_margin=Inches(.74)
    section.top_margin=Inches(.89);section.bottom_margin=Inches(.75)
    make_header(section)
    # First front-matter page: calm white space, no invented author attribution.
    doc.add_paragraph("\n\n")
    p=doc.add_paragraph(style="Title")
    p.alignment=WD_ALIGN_PARAGRAPH.CENTER
    p.add_run("BOT")
    text_par(doc,"L'INNOVAZIONE NON CHIEDE PERMESSO",10,AMBER,36,WD_ALIGN_PARAGRAPH.CENTER)
    text_par(doc,"Romanzo",12,MUTED,32,WD_ALIGN_PARAGRAPH.CENTER)
    text_par(doc,"Edizione illustrata  ·  v"+version,9,MUTED,0,WD_ALIGN_PARAGRAPH.CENTER)

    doc.add_page_break()
    p=doc.add_paragraph("Indice",style="Heading 1")
    p.paragraph_format.space_after=Pt(20)
    half=(len(chapters)+1)//2
    table=doc.add_table(rows=half,cols=2)
    table.autofit=False
    for row in range(half):
        for col in (0,1):
            idx=row+half*col
            cell=table.cell(row,col)
            cell.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER
            cell.width=Inches(2.16)
            if idx<len(chapters):
                n,title=chapters[idx]
                p=cell.paragraphs[0]
                p.paragraph_format.space_after=Pt(10)
                r=p.add_run(f"{n:02d}   ")
                r.font.name=SANS;r.font.size=Pt(9);r.bold=True;r.font.color.rgb=AMBER
                r=p.add_run(str(title))
                r.font.name=SANS;r.font.size=Pt(9);r.font.color.rgb=INK
            else:
                cell.text=""
    doc.add_paragraph()
    text_par(doc,"Un romanzo di fantascienza sociale",9,MUTED,0,WD_ALIGN_PARAGRAPH.CENTER)

def add_chapter(doc, meta, scenes, art_dir):
    n=int(meta["number"]);title=str(meta["title"])
    doc.add_page_break()
    p=doc.add_paragraph()
    p.paragraph_format.space_before=Pt(16)
    p.paragraph_format.space_after=Pt(17)
    r=p.add_run(f"CAPITOLO  {n:02d}")
    r.font.name=SANS;r.font.size=Pt(10);r.font.bold=True;r.font.color.rgb=AMBER

    p=doc.add_paragraph(style="Heading 1")
    p.paragraph_format.space_after=Pt(26)
    p.add_run(title)

    for i,body in enumerate(scenes):
        if i:
            p=doc.add_paragraph()
            p.alignment=WD_ALIGN_PARAGRAPH.CENTER
            p.paragraph_format.space_before=Pt(11)
            p.paragraph_format.space_after=Pt(13)
            r=p.add_run("◆   ◆   ◆")
            r.font.name=SANS;r.font.color.rgb=AMBER;r.font.size=Pt(8)
        # On the final illustrated plate the novel's last line must still be last.
        if n==35 and i==len(scenes)-1 and body.rstrip().endswith("Tutto tornò normale."):
            body=body.rstrip()[:-len("Tutto tornò normale.")].rstrip()
        add_body(doc,body)
    art=art_dir/f"chapter-{n:03d}.png"
    if not art.exists():
        raise RuntimeError(f"Missing chapter illustration: {art}")
    # Each end-of-chapter image is now a deliberately centered plate, not an
    # orphan thumbnail stranded at the top of an otherwise blank page.
    doc.add_page_break()
    p=doc.add_paragraph()
    p.paragraph_format.space_before=Pt(112)
    p.paragraph_format.space_after=Pt(16)
    p.alignment=WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.keep_together=True
    p.add_run().add_picture(str(art),width=Inches(4.50),height=Inches(2.531))
    label=doc.add_paragraph()
    label.alignment=WD_ALIGN_PARAGRAPH.CENTER
    label.paragraph_format.space_before=Pt(11)
    r=label.add_run(f"CAPITOLO {n:02d}  ·  {title}")
    r.font.name=SANS;r.font.size=Pt(8);r.font.color.rgb=MUTED
    if n==35:
        closing=doc.add_paragraph()
        closing.alignment=WD_ALIGN_PARAGRAPH.CENTER
        closing.paragraph_format.space_before=Pt(48)
        ending=closing.add_run("Tutto tornò normale.")
        ending.font.name=SERIF
        ending.font.size=Pt(15)
        ending.font.italic=True
        ending.font.color.rgb=INK

def render(output: Path,version: str,art_dir: Path):
    canonical=[]
    for folder in chapter_dirs():
        meta,_=load_document(folder/"chapter.md")
        if meta.get("canon")!="canon":
            continue
        scenes=[]
        for path in scene_files(folder):
            scene,body=load_document(path)
            if scene.get("canon")=="canon":
                scenes.append(body)
        if scenes:canonical.append((meta,scenes))
    if not canonical:
        raise RuntimeError("No canonical chapters")
    doc=Document()
    configure_styles(doc)
    add_title_pages(doc,[(int(meta["number"]),meta["title"]) for meta,_ in canonical],version,art_dir)
    for meta,scenes in canonical:
        add_chapter(doc,meta,scenes,art_dir)
    doc.core_properties.title="BOT"
    doc.core_properties.subject="L'innovazione non chiede permesso"
    doc.core_properties.language="it-IT"
    doc.core_properties.keywords="romanzo, fantascienza sociale, robotica"
    output.parent.mkdir(parents=True,exist_ok=True)
    doc.save(output)
    print(f"Typeset {len(canonical)} chapters into {output.relative_to(ROOT)}")

if __name__=="__main__":
    v=(ROOT/"VERSION").read_text(encoding="utf-8").strip()
    render(ROOT/"dist"/f"Bot-v{v}.docx",v,ROOT/"dist"/"illustrations")
